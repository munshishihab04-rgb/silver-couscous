const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("lp_lang") || "it");
  useEffect(() => { localStorage.setItem("lp_lang", lang); document.documentElement.lang = lang; }, [lang]);
  const t = dict[lang];
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);

export const money = (n) => new Intl.NumberFormat("it-IT", { style: "currency", currency: "EUR" }).format(n);
